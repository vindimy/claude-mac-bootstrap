#!/bin/bash
# Route the VS Code agent extensions — GitHub Copilot, Claude Code and Codex —
# through an SSH SOCKS5 tunnel, DNS included. The tunnel itself is not managed
# here; bring it up first, e.g.:
#
#   ssh -D 1080 -N -f user@remote_server_ip
#
# None of the three extensions can use a SOCKS proxy directly: Anthropic
# documents "Claude Code does not support SOCKS proxies", Copilot ships its own
# HTTP-only proxy client, and Codex's reqwest build has no `socks` feature.
# So this script runs privoxy as an HTTP-to-SOCKS5 bridge and points every tool
# at the bridge instead. privoxy's forward-socks5 hands the *hostname* to the
# SSH server, which resolves it there — no name lookup leaves this Mac.
#
# Reasoning, evidence and the manual equivalent of every step:
# docs/macos-vscode-socks-proxy.md
set -u

SOCKS_HOST="${SOCKS_HOST:-127.0.0.1}"
SOCKS_PORT="${SOCKS_PORT:-1080}"
BRIDGE_HOST=127.0.0.1
BRIDGE_PORT="${BRIDGE_PORT:-8118}"
BRIDGE_URL="http://$BRIDGE_HOST:$BRIDGE_PORT"
# Loopback only. The agents' localhost traffic (VS Code's IDE MCP server,
# OAuth callbacks) must never enter the tunnel.
NO_PROXY_LIST="${NO_PROXY_LIST:-localhost,127.0.0.1,::1}"

STATE_DIR="${MAC_BOOTSTRAP_HOME:-$HOME/.mac-bootstrap}/socks-proxy"
PRIVOXY_CONF="$STATE_DIR/privoxy.config"
BRIDGE_PID="$STATE_DIR/bridge.pid"
ENV_FILE="$STATE_DIR/proxy.env"
GUI_FLAG="$STATE_DIR/gui-env-set"
VSCODE_SETTINGS="${VSCODE_SETTINGS:-$HOME/Library/Application Support/Code/User/settings.json}"
VSCODE_BACKUP="$STATE_DIR/settings.json.before-socks-proxy"

# Every VS Code setting this script owns; `down` deletes exactly these.
VSCODE_KEYS='"http.proxy","http.proxySupport","http.proxyStrictSSL","http.noProxy"'

log()  { printf '%s\n' "$*"; }
warn() { printf 'warning: %s\n' "$*" >&2; }
err()  { printf 'error: %s\n' "$*" >&2; }

usage() {
  cat <<'USAGE'
usage: socks-proxy.sh <command>

  up [--gui]  Start the HTTP-to-SOCKS5 bridge and point VS Code, Copilot,
              Claude Code and Codex at it. --gui also exports the proxy to
              GUI apps via launchctl, so a Dock-launched VS Code inherits it.
  down        Stop the bridge and undo every change up made.
  status      Show tunnel, bridge, VS Code and environment state.
  verify [H]  Prove traffic leaves through the tunnel. With a hostname H that
              only the remote's DNS can resolve, also proves remote DNS.
  env         Print the export lines: eval "$(socks-proxy.sh env)"
  config      Print the privoxy bridge config this script generates.
  code [...]  Launch VS Code with the proxy environment applied.

Environment: SOCKS_HOST (127.0.0.1), SOCKS_PORT (1080), BRIDGE_PORT (8118),
NO_PROXY_LIST (localhost,127.0.0.1,::1).
USAGE
}

# --- tunnel and bridge -------------------------------------------------------

port_open() { nc -z -G 2 "$1" "$2" >/dev/null 2>&1; }

tunnel_up() { port_open "$SOCKS_HOST" "$SOCKS_PORT"; }

require_tunnel() {
  if tunnel_up; then return 0; fi
  err "no SOCKS listener on $SOCKS_HOST:$SOCKS_PORT — start the tunnel first:"
  err "  ssh -D $SOCKS_PORT -N -f user@remote_server_ip"
  return 1
}

# brew puts privoxy in sbin, which is often off a GUI app's PATH.
find_privoxy() {
  local p
  for p in "$(command -v privoxy 2>/dev/null)" \
           /opt/homebrew/opt/privoxy/sbin/privoxy \
           /usr/local/opt/privoxy/sbin/privoxy \
           /opt/homebrew/sbin/privoxy /usr/local/sbin/privoxy; do
    if [ -n "$p" ] && [ -x "$p" ]; then printf '%s\n' "$p"; return 0; fi
  done
  return 1
}

ensure_privoxy() {
  if find_privoxy >/dev/null; then return 0; fi
  if ! command -v brew >/dev/null 2>&1; then
    err "privoxy not found and Homebrew is not installed — install privoxy first"
    return 1
  fi
  log "socks-proxy: installing privoxy (the HTTP-to-SOCKS5 bridge)"
  brew install privoxy >/dev/null || { err "brew install privoxy failed"; return 1; }
  find_privoxy >/dev/null
}

# A deliberately bare config: no actionsfile and no filterfile, so privoxy
# forwards bytes and rewrites nothing. forward-socks5 (not forward-socks4) is
# the line that matters for privacy — privoxy's docs put it plainly: "With
# forward-socks5 the DNS resolution will happen on the remote server as well."
# The trailing "." means no parent HTTP proxy after the SOCKS hop.
privoxy_config_text() {
  cat <<EOF
# Generated by bin/socks-proxy.sh — edits are overwritten on the next 'up'.
listen-address $BRIDGE_HOST:$BRIDGE_PORT
forward-socks5 / $SOCKS_HOST:$SOCKS_PORT .
logdir $STATE_DIR
logfile privoxy.log
EOF
}

write_privoxy_config() {
  mkdir -p "$STATE_DIR" || return 1
  privoxy_config_text >"$PRIVOXY_CONF"
}

bridge_pid() {
  [ -f "$BRIDGE_PID" ] || return 1
  local pid
  pid="$(cat "$BRIDGE_PID" 2>/dev/null)"
  [ -n "$pid" ] || return 1
  kill -0 "$pid" 2>/dev/null || return 1
  printf '%s\n' "$pid"
}

bridge_start() {
  local bin
  if bridge_pid >/dev/null; then
    log "socks-proxy: bridge already running on $BRIDGE_URL"
    return 0
  fi
  if port_open "$BRIDGE_HOST" "$BRIDGE_PORT"; then
    err "port $BRIDGE_PORT is already in use by something else — set BRIDGE_PORT"
    return 1
  fi
  bin="$(find_privoxy)" || { err "privoxy not found"; return 1; }
  write_privoxy_config || return 1
  "$bin" --pidfile "$BRIDGE_PID" "$PRIVOXY_CONF" || { err "privoxy failed to start"; return 1; }
  local i=0
  while [ "$i" -lt 25 ]; do
    if port_open "$BRIDGE_HOST" "$BRIDGE_PORT"; then
      log "socks-proxy: bridge listening on $BRIDGE_URL -> socks5://$SOCKS_HOST:$SOCKS_PORT"
      return 0
    fi
    i=$((i + 1))
  done
  err "bridge did not come up — see $STATE_DIR/privoxy.log"
  return 1
}

bridge_stop() {
  local pid
  if pid="$(bridge_pid)"; then
    kill "$pid" 2>/dev/null
    log "socks-proxy: bridge stopped"
  fi
  rm -f "$BRIDGE_PID"
}

# --- VS Code settings --------------------------------------------------------

# Copilot reads http.proxy and speaks only to HTTP proxies, so it gets the
# bridge URL, never a socks5h:// one. The same setting covers the extension
# host's own requests.
vscode_settings_apply() {
  local tmp
  if ! command -v jq >/dev/null 2>&1; then
    warn "jq not found — add these to VS Code user settings by hand:"
    warn "  \"http.proxy\": \"$BRIDGE_URL\", \"http.proxySupport\": \"override\""
    return 0
  fi
  if [ ! -f "$VSCODE_SETTINGS" ]; then
    mkdir -p "$(dirname "$VSCODE_SETTINGS")" || return 1
    printf '{}\n' >"$VSCODE_SETTINGS"
  fi
  if ! jq -e . "$VSCODE_SETTINGS" >/dev/null 2>&1; then
    warn "$VSCODE_SETTINGS is not plain JSON (comments?) — add by hand:"
    warn "  \"http.proxy\": \"$BRIDGE_URL\", \"http.proxySupport\": \"override\""
    return 0
  fi
  [ -f "$VSCODE_BACKUP" ] || cp "$VSCODE_SETTINGS" "$VSCODE_BACKUP"
  tmp="$VSCODE_SETTINGS.socks-proxy.tmp"
  jq --arg p "$BRIDGE_URL" --arg n "$NO_PROXY_LIST" \
     '. + {"http.proxy": $p, "http.proxySupport": "override",
           "http.proxyStrictSSL": true, "http.noProxy": ($n | split(","))}' \
     "$VSCODE_SETTINGS" >"$tmp" || { rm -f "$tmp"; return 1; }
  mv "$tmp" "$VSCODE_SETTINGS"
  log "socks-proxy: VS Code http.proxy -> $BRIDGE_URL"
}

vscode_settings_revert() {
  local tmp
  if ! command -v jq >/dev/null 2>&1 || [ ! -f "$VSCODE_SETTINGS" ]; then return 0; fi
  if ! jq -e . "$VSCODE_SETTINGS" >/dev/null 2>&1; then
    warn "$VSCODE_SETTINGS is not plain JSON — remove the http.* proxy keys by hand"
    return 0
  fi
  tmp="$VSCODE_SETTINGS.socks-proxy.tmp"
  jq "del(.[$VSCODE_KEYS])" "$VSCODE_SETTINGS" >"$tmp" || { rm -f "$tmp"; return 1; }
  mv "$tmp" "$VSCODE_SETTINGS"
  log "socks-proxy: VS Code proxy settings removed"
}

# --- environment for the spawned CLIs ---------------------------------------

# The Claude Code and Codex extensions each launch their CLI as a child of the
# VS Code process, so the CLIs read the proxy from VS Code's environment —
# http.proxy never reaches them.
env_lines() {
  printf 'export HTTP_PROXY="%s"\n'  "$BRIDGE_URL"
  printf 'export HTTPS_PROXY="%s"\n' "$BRIDGE_URL"
  printf 'export http_proxy="%s"\n'  "$BRIDGE_URL"
  printf 'export https_proxy="%s"\n' "$BRIDGE_URL"
  printf 'export ALL_PROXY="%s"\n'   "$BRIDGE_URL"
  printf 'export NO_PROXY="%s"\n'    "$NO_PROXY_LIST"
  printf 'export no_proxy="%s"\n'    "$NO_PROXY_LIST"
}

env_file_write() {
  mkdir -p "$STATE_DIR" || return 1
  {
    printf '# Generated by bin/socks-proxy.sh. Source it, or use socks-proxy.sh code.\n'
    env_lines
  } >"$ENV_FILE"
  log "socks-proxy: environment written to $ENV_FILE"
}

# launchctl reaches apps launched from the Dock or Spotlight afterwards. It is
# session-wide (every GUI app, not just VS Code) and is lost at logout.
gui_env_apply() {
  launchctl setenv HTTP_PROXY "$BRIDGE_URL"
  launchctl setenv HTTPS_PROXY "$BRIDGE_URL"
  launchctl setenv ALL_PROXY "$BRIDGE_URL"
  launchctl setenv NO_PROXY "$NO_PROXY_LIST"
  mkdir -p "$STATE_DIR" && : >"$GUI_FLAG"
  log "socks-proxy: proxy exported to GUI apps (restart VS Code to pick it up)"
}

gui_env_revert() {
  [ -f "$GUI_FLAG" ] || return 0
  launchctl unsetenv HTTP_PROXY
  launchctl unsetenv HTTPS_PROXY
  launchctl unsetenv ALL_PROXY
  launchctl unsetenv NO_PROXY
  rm -f "$GUI_FLAG"
  log "socks-proxy: proxy removed from the GUI environment"
}

# --- commands ----------------------------------------------------------------

cmd_up() {
  local gui=0
  if [ "${1:-}" = "--gui" ]; then gui=1; fi
  require_tunnel || return 1
  ensure_privoxy || return 1
  bridge_start || return 1
  vscode_settings_apply || return 1
  env_file_write || return 1
  if [ "$gui" = 1 ]; then gui_env_apply; fi
  log ""
  log "Restart VS Code so the extension host and the CLIs it spawns pick this up."
  log "Then check it with: $0 verify"
}

cmd_down() {
  bridge_stop
  vscode_settings_revert
  gui_env_revert
  rm -f "$ENV_FILE"
  log "socks-proxy: down — restart VS Code to drop the proxy"
}

cmd_status() {
  local pid state
  if tunnel_up; then state="up"; else state="DOWN"; fi
  printf '%-22s %s\n' "SSH SOCKS tunnel" "$state ($SOCKS_HOST:$SOCKS_PORT)"
  if pid="$(bridge_pid)"; then state="up (pid $pid)"; else state="DOWN"; fi
  printf '%-22s %s\n' "HTTP bridge" "$state ($BRIDGE_URL)"
  if command -v jq >/dev/null 2>&1 && [ -f "$VSCODE_SETTINGS" ] &&
     jq -e . "$VSCODE_SETTINGS" >/dev/null 2>&1; then
    state="$(jq -r '."http.proxy" // "unset"' "$VSCODE_SETTINGS")"
  else
    state="unknown"
  fi
  printf '%-22s %s\n' "VS Code http.proxy" "$state"
  if [ -f "$ENV_FILE" ]; then state="$ENV_FILE"; else state="not written"; fi
  printf '%-22s %s\n' "CLI environment" "$state"
  if [ -f "$GUI_FLAG" ]; then state="set"; else state="not set"; fi
  printf '%-22s %s\n' "GUI (launchctl) env" "$state"
}

# Egress proof: the public IP seen through the bridge must be the remote's,
# not this Mac's. The optional hostname proves the remote resolves names.
cmd_verify() {
  local host direct tunnelled rc=0
  host="${1:-}"
  require_tunnel || return 1
  if ! bridge_pid >/dev/null; then err "bridge is not running — run: $0 up"; return 1; fi

  direct="$(curl -fsS --max-time 15 https://api.ipify.org 2>/dev/null)" ||
    warn "could not read the direct public IP"
  tunnelled="$(curl -fsS --max-time 20 --proxy "$BRIDGE_URL" https://api.ipify.org 2>/dev/null)" || {
    err "no answer through the bridge — is the SSH tunnel still alive?"
    return 1
  }
  printf '%-22s %s\n' "direct public IP" "${direct:-unknown}"
  printf '%-22s %s\n' "public IP via tunnel" "$tunnelled"
  if [ -n "$direct" ] && [ "$direct" = "$tunnelled" ]; then
    err "same IP both ways — traffic is NOT leaving through the tunnel"
    rc=1
  else
    log "OK: traffic egresses from the remote host"
  fi

  if [ -n "$host" ]; then
    if curl -fsS -o /dev/null --max-time 20 --proxy "$BRIDGE_URL" "https://$host" 2>/dev/null; then
      log "OK: $host resolved and reached through the tunnel (remote DNS)"
    else
      err "$host did not resolve or answer through the tunnel"
      rc=1
    fi
  fi
  return "$rc"
}

cmd_code() {
  if [ ! -f "$ENV_FILE" ]; then err "run '$0 up' first"; return 1; fi
  # shellcheck source=/dev/null
  . "$ENV_FILE"
  exec code "$@"
}

case "${1:-}" in
  up)     shift; cmd_up "$@" ;;
  down)   cmd_down ;;
  status) cmd_status ;;
  verify) shift; cmd_verify "$@" ;;
  env)    env_lines ;;
  config) privoxy_config_text ;;
  code)   shift; cmd_code "$@" ;;
  -h|--help|help|"") usage ;;
  *)      err "unknown command: $1"; usage >&2; exit 2 ;;
esac
